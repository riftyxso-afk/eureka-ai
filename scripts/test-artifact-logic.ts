import assert from "node:assert/strict";
import { ChatRequestScope, editMessageArtifact, messageArtifacts, parseArtifactMessage } from "../lib/assistant/artifacts";
import type { AssistantChatMessage } from "../lib/assistant/types";

const raw = 'Before <artifact type="markdown" title="Notes">old</artifact> between <artifact type="terminal">log</artifact> after';
const message: AssistantChatMessage = { id: "message-1", sessionId: "session-1", role: "assistant", content: raw, mentions: [], sources: [], model: null, createdAt: "2026-01-01" };
assert.equal(parseArtifactMessage(raw).chat, "Before  between  after");
assert.equal(parseArtifactMessage("Before <arti", true).chat, "Before ");
assert.equal(parseArtifactMessage("Before <arti").chat, "Before <arti");
assert.equal(parseArtifactMessage('<artifact type="unknown">literal</artifact>').chat, '<artifact type="unknown">literal</artifact>');
const artifacts = messageArtifacts(message);
assert.equal(artifacts.length, 2);
assert.equal(artifacts[0].id, "message-1:artifact:0");
assert.deepEqual(messageArtifacts(message), artifacts);
const edited = editMessageArtifact(raw, 0, "new text\nsecond line");
assert.equal(parseArtifactMessage(edited).chat, parseArtifactMessage(raw).chat);
assert.equal(messageArtifacts({ ...message, content: edited })[0].version, 2);
assert.equal(messageArtifacts({ ...message, content: edited })[0].content, "new text\nsecond line");
assert.equal(messageArtifacts({ ...message, content: editMessageArtifact(edited, 0, "third") })[0].version, 3);
assert.throws(() => editMessageArtifact(raw, 1, "not markdown"));
assert.throws(() => editMessageArtifact(raw, 4, "missing"));
assert.throws(() => editMessageArtifact(raw, 0, "</artifact>injection"));
assert.deepEqual(messageArtifacts({ ...message, content: "No artifact" }), []);
const scope = new ChatRequestScope();
const first = scope.enter("a");
assert.equal(scope.current("a", first), true);
const second = scope.enter("b");
assert.equal(scope.current("a", first), false);
assert.equal(scope.current("b", second), true);
const newer = scope.enter("b");
assert.equal(scope.current("b", second), false);
assert.equal(scope.current("b", newer), true);
scope.enter(null);
assert.equal(scope.current("b", newer), false);
console.log("PASS: artifact parsing, stable history identity, persisted versions, edit validation, empty history, session and overlapping request guards");
